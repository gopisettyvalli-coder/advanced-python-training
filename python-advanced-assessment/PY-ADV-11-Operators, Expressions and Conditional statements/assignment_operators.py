print("====== Assignment operators ======")


first_number=int(input("Enter the first number:"))
second_number=int(input("Enter the second number:"))

first_number += second_number
print("first_number+=second_number:", first_number)


first_number -= second_number
print("first_number-=second_number:", first_number)

first_number *= second_number
print("first_number*=second_number:", first_number)

first_number/=second_number
print("first_number/=second_number:", first_number)

first_number%=second_number
print("first_number%=second_number:", first_number)

first_number//=second_number
print("first_number//=second_number:", first_number)
