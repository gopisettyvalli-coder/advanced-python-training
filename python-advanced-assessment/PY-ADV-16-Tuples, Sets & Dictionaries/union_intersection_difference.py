# union
num1={10,20,30}
num2={15,25,35}

print("Union of sets:",num1.union(num2))
print("================================")

# intersection
num1={15,25,35,45}
num2={15,20,30,35}

print("Intersection of two sets:", num1.intersection(num2))
print("================================")

# difference
num1={10,20,30,40}
num2={5,10,15,20}

print("Difference between twe sets:", num1.difference(num2))