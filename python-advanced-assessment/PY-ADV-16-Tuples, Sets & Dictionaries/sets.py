# creating set
nums={12,45,99,45}
print("Set:", nums)
print("================================")

# type of a set
nums={11,12,15,78}
print(type(nums))
print("================================")

# remove duplicates
nums={12,10,15,10,2,4,5,2,4,2}
print("New Set:", nums)
print("================================")


# adding elements
numbers={10,20,30,40}
numbers.add(60)
print("Numbers set:", numbers)
print("================================")

# remove element
numbers={20,15,10,35,50,20,56}
numbers.remove(50)
print("New Set:", numbers)
print("================================")

# union of two sets
a={10,20,30}
b={50,60,70}
print(a.union(b))
print("================================")

# intersection
a={10,20,30,40}
b=(40,50,60)
print(a.intersection(b))

